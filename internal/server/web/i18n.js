  function languages() {
    return Object.keys(CATALOG);
  }

  // An unknown key returns itself: a missing translation shows which string is
  // missing instead of an empty element.
  function translate(catalog, lang, key, arg) {
    const table = catalog[lang] || catalog[FALLBACK_LANGUAGE];
    const value = table[key];
    if (typeof value === "function") return value(arg);
    return value != null ? value : key;
  }

  // A stored choice wins; otherwise the browser's own language decides, and
  // anything else falls back.
  function pickLanguage(stored, requested) {
    if (CATALOG[stored]) return stored;
    const tag = String(requested || "").toLowerCase();
    for (const lang of languages()) {
      if (tag === lang || tag.startsWith(lang + "-")) return lang;
    }
    return "en";
  }

  return { CATALOG, FALLBACK_LANGUAGE, languages, translate, pickLanguage };
